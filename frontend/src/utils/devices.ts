export type Region = {
  name: string;
  kind: "flash" | "xip" | "ram" | "ccm" | "virt" | "eeprom";
  base: number;
  size: number;
  color: string;
};

export type Device = {
  id: string;
  name: string;
  mcu: boolean;
  vendor: string;
  family?: string;
  architecture: string; // e.g. ARM Cortex-M4, RISC-V RV32, Xtensa LX6, AVR, etc.
  core: string;
  endianness?: "little" | "big";
  fpu?: string;
  clockSpeed?: string;
  flashSize?: number;
  sramSize?: number;
  eepromSize?: number;
  vectorTableAddr?: number;
  flashBaseAddr?: number;
  ramBaseAddr?: number;
  interruptCount?: number;
  regions: Region[];
  rtos?: string[];
  defaultToolchain?: string;
  supportedFormats?: string[];
  datasheetUrl?: string;
  refManualUrl?: string;
  description?: string;
  boardImage?: string;
  detection?: string;
  possibleMatches?: string[];
};

