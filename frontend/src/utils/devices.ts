const np2 = (n: number) => Math.pow(2, Math.ceil(Math.log2(Math.max(n, 1))));
const minAddr = (secs: any[], names: string[]) => {
  const m = secs.filter(s => names.includes(s.name) && s.size > 0).map(s => s.addr >>> 0);
  return m.length ? Math.min(...m) : 0;
};

// AUTOMATIC DEVICE DETECTION WITH POSSIBLE MATCHES
export function detectDevice(res: { arch: string; elf_class?: number; sections: any[]; summary: Record<string, number> }): Device {
  const arch = res.arch || "";
  const usedF = (res.summary[".text"] || 0) + (res.summary[".rodata"] || 0);

  if (/xtensa/i.test(arch)) {
    return { ...DB.esp32, detection: "Xtensa architecture signature", possibleMatches: ["esp32", "esp32s2", "esp32s3"] };
  }

  if (/x86|80386|i386|amd64/i.test(arch)) {
    const t = minAddr(res.sections, [".text", ".init", ".rodata"]) || 0x1000;
    const d = minAddr(res.sections, [".data", ".bss"]) || 0x4000;
    return {
      ...DB.generic_x86,
      name: `${arch} · host binary`,
      detection: "x86 Host ELF Header",
      regions: [r(".text / .rodata", "virt", t, usedF || 1), r(".data / .bss", "virt", d, (res.summary[".data"] || 0) + (res.summary[".bss"] || 0) || 1)],
    };
  }

  if (/aarch64|arm64/i.test(arch)) {
    return { ...DB.generic_aarch64, detection: "AArch64 ELF Header" };
  }

  const t = (minAddr(res.sections, [".text", ".init", ".rodata", ".isr_vector"]) || 0) >>> 0;
  const top = t & 0xff000000;

  if (top === 0x08000000) {
    if (usedF <= 64 * K) return { ...DB.stm32f103c8, detection: "Flash address 0x08000000 + 64KB footprint", possibleMatches: ["stm32f103c8", "stm32f0", "stm32g071"] };
    if (usedF <= 256 * K) return { ...DB.stm32f303, detection: "Flash address 0x08000000 + 256KB footprint", possibleMatches: ["stm32f303", "stm32l476", "stm32g474"] };
    if (usedF <= 1024 * K) return { ...DB.stm32f407, detection: "Flash address 0x08000000 + 1MB footprint", possibleMatches: ["stm32f407", "stm32l476", "stm32wb55"] };
    return { ...DB.stm32h743, detection: "Flash address 0x08000000 + High capacity footprint", possibleMatches: ["stm32h743", "stm32f767", "stm32u585"] };
  }

  if (top === 0x10000000) return { ...DB.rp2040, detection: "Flash XIP address 0x10000000", possibleMatches: ["rp2040", "rp2350"] };
  if (top === 0x00000000) return usedF <= 256 * K ? { ...DB.samd21, detection: "Flash address 0x00000000", possibleMatches: ["samd21", "nrf52832"] } : { ...DB.nrf52840, detection: "Flash address 0x00000000", possibleMatches: ["nrf52840", "nrf5340"] };
  if (top === 0x40000000 || top === 0x3f000000) return { ...DB.esp32c3, detection: "RISC-V memory map layout", possibleMatches: ["esp32c3", "esp32c6", "esp32h2"] };

  const fb = t & 0xfff00000;
  const db = (minAddr(res.sections, [".data", ".bss"]) || 0x20000000) >>> 0;
  return {
    ...DB.generic_cortex_m,
    name: "Generic Cortex-M Profile",
    detection: "Memory layout heuristic",
    regions: [
      r("FLASH", "flash", fb, np2(usedF) * 2 || 64 * K),
      r("SRAM", "ram", db & 0xfff00000, np2((res.summary[".data"] || 0) + (res.summary[".bss"] || 0)) * 2 || 16 * K),
    ],
    possibleMatches: ["generic_cortex_m", "stm32f407", "nrf52840", "rp2040"],
  };
}

export const inRegion = (rg: Region, addr: number) => {
  const a = addr >>> 0;
  return a >= rg.base && a < rg.base + rg.size;
};

export const colRegions = (d: Device, col: "flash" | "ram") =>
  d.regions.filter(rg => (col === "flash" ? rg.kind === "flash" || rg.kind === "xip" : rg.kind === "ram" || rg.kind === "ccm"));

export const usedIn = (d: Device, secs: any[], kinds: Region["kind"][]) => {
  const rgs = d.regions.filter(rg => kinds.includes(rg.kind));
  return secs.filter(s => s.size > 0 && rgs.some(rg => inRegion(rg, s.addr))).reduce((a, s) => a + s.size, 0);
};

export function fmt(b: number): string {
  if (b >= M) {
    const mb = b / M;
    return (Number.isInteger(mb) ? mb : mb.toFixed(1)) + "M";
  }
  if (b >= K) {
    const kb = b / K;
    return (Number.isInteger(kb) ? kb : kb.toFixed(1)) + "K";
  }
  return b + "B";
}
